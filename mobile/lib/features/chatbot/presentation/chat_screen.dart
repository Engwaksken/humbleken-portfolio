import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../../core/api/api_exception.dart';
import '../../../core/widgets/layout.dart';
import '../../../core/widgets/state_views.dart';
import '../../site/data/site_repository.dart';
import '../data/chat_repository.dart';

class ChatScreen extends ConsumerStatefulWidget {
  const ChatScreen({super.key});

  @override
  ConsumerState<ChatScreen> createState() => _ChatScreenState();
}

class _ChatScreenState extends ConsumerState<ChatScreen> {
  final _input = TextEditingController();
  final _scroll = ScrollController();
  final List<ChatMessage> _messages = [];
  bool _busy = false;
  String? _error;

  @override
  void dispose() {
    _input.dispose();
    _scroll.dispose();
    super.dispose();
  }

  Future<void> _send() async {
    final text = _input.text.trim();
    if (text.isEmpty || _busy) return;
    setState(() {
      _messages.add(ChatMessage(ChatRole.user, text));
      _busy = true;
      _error = null;
      _input.clear();
    });
    _scrollToEnd();
    try {
      final reply = await ref.read(chatRepositoryProvider).send(_messages);
      if (!mounted) return;
      setState(() => _messages.add(ChatMessage(ChatRole.assistant, reply)));
    } catch (e) {
      if (!mounted) return;
      final notAvailable = e is ApiException && e.isNotFound;
      setState(() {
        // Put the question back so it can be retried.
        _messages.removeLast();
        _input.text = text;
        _error = notAvailable ? 'The assistant is not available right now.' : ApiException.messageOf(e);
      });
    } finally {
      if (mounted) setState(() => _busy = false);
      _scrollToEnd();
    }
  }

  void _scrollToEnd() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (!_scroll.hasClients) return;
      final reduceMotion = MediaQuery.disableAnimationsOf(context);
      final target = _scroll.position.maxScrollExtent;
      if (reduceMotion) {
        _scroll.jumpTo(target);
      } else {
        _scroll.animateTo(target, duration: const Duration(milliseconds: 250), curve: Curves.easeOut);
      }
    });
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final scheme = theme.colorScheme;
    final enabled = ref.watch(siteConfigProvider.select((s) => s.features.chatbot));

    return Scaffold(
      appBar: AppBar(title: const Text('AI assistant')),
      body: !enabled
          ? const EmptyView(message: 'The assistant is not available right now.', icon: Icons.smart_toy_outlined)
          : Column(
              children: [
                Expanded(
                  child: ListView(
                    controller: _scroll,
                    padding: const EdgeInsets.all(16),
                    children: [
                      ContentWidth(
                        maxWidth: 760,
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.stretch,
                          children: [
                            Text(
                              'Ask a question about our services or a technical problem. '
                              'Answers are generated by AI and may be inaccurate; for anything important, '
                              'send an enquiry or open a support ticket.',
                              style: theme.textTheme.bodyMedium?.copyWith(color: scheme.onSurfaceVariant),
                            ),
                            const SizedBox(height: 16),
                            for (final m in _messages) _Bubble(message: m),
                            if (_busy) const LoadingView(label: 'Assistant is replying'),
                          ],
                        ),
                      ),
                    ],
                  ),
                ),
                Material(
                  color: scheme.surfaceContainer,
                  child: SafeArea(
                    top: false,
                    child: Padding(
                      padding: const EdgeInsets.fromLTRB(16, 12, 8, 12),
                      child: Row(
                        crossAxisAlignment: CrossAxisAlignment.end,
                        children: [
                          Expanded(
                            child: TextField(
                              controller: _input,
                              minLines: 1,
                              maxLines: 4,
                              textInputAction: TextInputAction.send,
                              onSubmitted: (_) => _send(),
                              decoration: InputDecoration(
                                labelText: 'Your question',
                                errorText: _error,
                                errorMaxLines: 3,
                              ),
                            ),
                          ),
                          const SizedBox(width: 4),
                          IconButton.filled(
                            onPressed: _busy ? null : _send,
                            tooltip: 'Send question',
                            icon: const Icon(Icons.send),
                          ),
                        ],
                      ),
                    ),
                  ),
                ),
              ],
            ),
    );
  }
}

class _Bubble extends StatelessWidget {
  const _Bubble({required this.message});
  final ChatMessage message;

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final mine = message.role == ChatRole.user;
    final bg = mine ? scheme.primaryContainer : scheme.surfaceContainerHigh;
    final fg = mine ? scheme.onPrimaryContainer : scheme.onSurface;
    return Align(
      alignment: mine ? Alignment.centerRight : Alignment.centerLeft,
      child: ConstrainedBox(
        constraints: BoxConstraints(maxWidth: MediaQuery.sizeOf(context).width * 0.85),
        child: Container(
          margin: const EdgeInsets.only(bottom: 10),
          padding: const EdgeInsets.all(12),
          decoration: BoxDecoration(color: bg, borderRadius: BorderRadius.circular(14)),
          child: SelectableText(
            message.content,
            semanticsLabel: '${mine ? 'You' : 'Assistant'}: ${message.content}',
            style: TextStyle(color: fg),
          ),
        ),
      ),
    );
  }
}
